<?php

//------------------------------------------------------------------------------
// File:         TagInfoXML.pm
//
// Description:  Read/write tag information XML database
//
// Revisions:    2009/01/28 - P. Harvey Created
//
// PHP port of Image::ExifTool::TagInfoXML 1.38 (Write() and its helpers only: the Lang module
// generators BuildLangModules() and WriteLangModule() are developer tools and are not ported).
//------------------------------------------------------------------------------

namespace Image\ExifTool;

final class TagInfoXML
{
    public static $VERSION = '1.38';

    private static $numbersFirst = 1;   // set to -1 to sort numbers last, or 2 to put negative numbers last
    private static $caseInsensitive;    // used internally by sort routine

    // write groups that don't represent real family 1 group names
    private const FAKE_WRITE_GROUP = [
        'Comment' => 1,   // (JPEG Comment)
        'colr' => 1,      // (Jpeg2000 'colr' box)
    ];

    //------------------------------------------------------------------------------
    // Utility to print tag information database as an XML list
    // Inputs: 0) output file name (null to send to $out), 1) group name (may be null),
    //         2) options hash ('Flags','NoDesc','Lang'), 3) output stream for the console
    // Returns: true on success
    public static function Write($file = null, $group = null, array $opts = [], $out = null): bool
    {
        $et = new ExifTool();
        $langInfo = [];
        $langs = [];
        $defaultLang = null;
        $groups = $group ? explode(':', $group) : [];

        ExifTool::LoadAllTables();   // first load all our tables
        QuickTime::LoadWriteQuickTime();   // (Perl AUTOLOADs WriteQuickTime.pl, which edits the QuickTime tables)
        if (empty($opts['NoDesc'])) {
            $defaultLang = Vars\ExifTool::$defaultLang;
            self::LoadLangModules($langInfo, $opts['Lang'] ?? null); // load necessary Lang modules
            if (!empty($opts['Lang'])) {
                $langs = array_values(array_filter(array_keys($langInfo),
                    fn($l) => preg_match('/^' . $opts['Lang'] . '$/i', (string) $l)));
            } else {
                $langs = array_map('strval', array_keys($langInfo));
                sort($langs, SORT_STRING);
            }
        }
        if ($file !== null) {
            $fp = @fopen($file, 'w');
            if (!$fp) return false;
        } else {
            $fp = $out ?? STDOUT;
        }
        $p = static fn(string $s) => fwrite($fp, $s);
        $p("<?xml version='1.0' encoding='UTF-8'?>\n");
        $p('<!-- Generated by Image::ExifTool ' . ExifTool::$VERSION . " -->\n");
        $p("<taginfo>\n\n");

        // loop through all tables and save tag names to %allTags hash
        $tableNames = array_map('strval', array_keys(ExifTool::$allTables));
        sort($tableNames, SORT_STRING);
        foreach ($tableNames as $tableName) {
            $table = ExifTool::GetTagTable($tableName);
            $grps = $table['GROUPS'];
            $didTag = null;
            // sort in same order as tag name documentation
            self::$caseInsensitive = str_contains($tableName, '::XMP::');
            // get list of languages defining elements in this table
            $isBinary = ($table['PROCESS_PROC'] and
                         $table['PROCESS_PROC'] === 'Image\ExifTool\ExifTool::ProcessBinaryData');
            // generate flattened tag names for structure fields if this is an XMP table
            if ($table['GROUPS'] and ($table['GROUPS'][0] ?? null) === 'XMP') {
                XMP::AddFlattenedTags($table);
            }
            self::$numbersFirst = 2;
            if ($table['VARS'] and !empty($table['VARS']['ALPHA_FIRST'])) self::$numbersFirst = -1;
            $keys = array_map('strval', ExifTool::TagTableKeys($table));
            usort($keys, [self::class, 'NumbersFirst']);
            self::$numbersFirst = 1;
            // loop through all tag ID's in this table
            foreach ($keys as $tagID) {
                $infoArray = ExifTool::GetTagInfoList($table, $tagID);
                $xmlID = XMP::FullEscapeXML($tagID);
                // get a list of languages defining elements for this ID
                for ($index = 0; $index < count($infoArray); ++$index) {
                    $tagInfo = $infoArray[$index];
                    // don't list subdirectories unless they are writable
                    if (!($tagInfo->Writable or $tagInfo->SubDirectory === null)) continue;   // (an empty [] is a Perl {}, true)
                    if ($tagInfo->Hidden) continue;
                    // (Validate.pm isn't loaded by exiftool, but the generated Extra table has its tag)
                    if ($name_ = $tagInfo->Name and $name_ === 'Validate' and !class_exists(__NAMESPACE__ . '\\Validate', false)) continue;
                    if ($groups) {
                        $tg = $et->GetGroup($tagInfo);
                        foreach ($groups as $g) {
                            $found = false;
                            foreach ($tg as $t) {
                                if (@preg_match('/^' . str_replace('/', '\/', $g) . '$/i', (string) $t)) {
                                    $found = true;
                                    break;
                                }
                            }
                            if (!$found) continue 2;
                        }
                    }
                    if (!$didTag) {
                        $tname = $table['SHORT_NAME'];
                        $p("<table name='{$tname}' g0='{$grps[0]}' g1='{$grps[1]}' g2='{$grps[2]}'>\n");
                        if (empty($opts['NoDesc'])) {
                            // print table description
                            $desc = $table['TABLE_DESC'];
                            if (!$desc) {
                                $desc = preg_replace('/::Main$/', '', $tname);
                                $desc = str_replace('::', ' ', $desc);
                            }
                            // print alternate language descriptions
                            $p(" <desc lang='en'>$desc</desc>\n");
                            foreach ($langs as $l) {
                                $desc = $langInfo[$l][$tableName] ?? null;
                                if (!$desc) continue;
                                $desc = XMP::EscapeXML($desc);
                                $p(" <desc lang='{$l}'>$desc</desc>\n");
                            }
                        }
                        $didTag = 1;
                    }
                    $name = $tagInfo->Name;
                    $ind = count($infoArray) > 1 ? " index='{$index}'" : '';
                    $format = $tagInfo->Writable ?: $table['WRITABLE'];
                    $writable = $format ? 'true' : 'false';
                    // check our conversions to make sure we can really write this tag
                    if ($writable === 'true') {
                        if ($tagInfo->Writable !== null and !$tagInfo->Writable) $writable = 'false';
                        foreach (['PrintConv', 'ValueConv'] as $cv) {
                            $conv = $tagInfo->$cv;
                            if (!$conv) continue;
                            if ($tagInfo->{$cv . 'Inv'}) continue;
                            if (is_array($conv) or $conv instanceof ConvList) continue;
                            if ($tagInfo->WriteAlso) continue;
                            $writable = 'false';
                            break;
                        }
                    }
                    if (!$format or Perl::str($format) === '1') $format = $tagInfo->Format ?: $table['FORMAT'];
                    if ($tagInfo->Struct) $format = 'struct';
                    if ($format !== null) {
                        $format = Perl::str($format);
                        $format = preg_replace('/\[.*\$.*\]/s', '', $format, 1);   // remove expressions from format
                        if ($format === '2') $format = 'undef'; // (special case)
                    } elseif ($isBinary) {
                        $format = 'int8u';
                    } else {
                        $format = '?';
                    }
                    $count = '';
                    if (preg_match('/\[.*?(\d*)\]$/s', $format, $m)) {
                        $format = preg_replace('/\[.*?(\d*)\]$/s', '', $format, 1);
                        if (strlen($m[1])) $count = " count='{$m[1]}'";
                    } elseif ($tagInfo->Count and $tagInfo->Count > 1) {
                        $count = " count='{$tagInfo->Count}'";
                    }
                    $tgroups = $et->GetGroup($tagInfo);
                    $writeGroup = $tagInfo->WriteGroup ?: $table['WRITE_GROUP'];
                    // use common write group for group 1 (unless fake)
                    if ($writeGroup and empty(self::FAKE_WRITE_GROUP[$writeGroup])) $tgroups[1] = $writeGroup;
                    // add group names if different from table defaults
                    $grp = '';
                    for ($fam = 0; $fam < 3; ++$fam) {
                        if (($tgroups[$fam] ?? null) !== ($grps[$fam] ?? null)) $grp .= " g$fam='{$tgroups[$fam]}'";
                    }
                    // add flags if necessary
                    if (!empty($opts['Flags'])) {
                        $flags = [];
                        foreach (['Avoid', 'Binary', 'List', 'Mandatory', 'Unknown'] as $f) {
                            if ($tagInfo->$f) $flags[] = $f;
                        }
                        if ($tagInfo->List and preg_match('/^(Alt|Bag|Seq)$/', Perl::str($tagInfo->List))) $flags[] = $tagInfo->List;
                        if ($tagInfo->Flat !== null) $flags[] = 'Flattened';
                        if ($tagInfo->Protected and $tagInfo->Protected & 0x01) $flags[] = 'Unsafe';
                        if ($tagInfo->Protected and $tagInfo->Protected & 0x02) $flags[] = 'Protected';
                        if ($tagInfo->Permanent or
                            ($tgroups[0] === 'MakerNotes' and $tagInfo->Permanent === null)) $flags[] = 'Permanent';
                        if ($flags) {
                            $flags = array_map('strval', $flags);
                            sort($flags, SORT_STRING);
                            $grp = " flags='" . implode(',', $flags) . "'$grp";
                        }
                        // add parent structure tag ID
                        if ($tagInfo->ParentTagInfo) $grp .= " struct='{$tagInfo->ParentTagInfo->TagID}'";
                    }
                    $p(" <tag id='{$xmlID}' name='{$name}'$ind type='{$format}'$count writable='{$writable}'$grp");
                    if (!empty($opts['NoDesc'])) {
                        // short output format
                        $p("/>\n");   // empty tag element
                        continue;     // no descriptions or values
                    } else {
                        $p('>');
                    }
                    $desc = $tagInfo->Description;
                    if ($desc === null) $desc = ExifTool::MakeDescription($name);
                    // add alternate language descriptions and get references
                    // to alternate language PrintConv hashes
                    $altDescr = '';
                    $langConv = [];
                    foreach ($langs as $l) {
                        $ld = $langInfo[$l][$name] ?? null;
                        if (!$ld) continue;
                        if (is_array($ld)) {
                            $langConv[$l] = $ld['PrintConv'] ?? null;
                            $ld = $ld['Description'] ?? null;
                            if (!$ld) continue;
                        }
                        // ignore descriptions that are the same as the default language
                        if ($ld === $desc) continue;
                        $ld = XMP::EscapeXML($ld);
                        $altDescr .= "\n  <desc lang='{$l}'>$ld</desc>";
                    }
                    // print tag descriptions
                    $desc = XMP::EscapeXML($desc);
                    if (empty($opts['Lang']) or !$altDescr) {
                        $p("\n  <desc lang='{$defaultLang}'>$desc</desc>");
                    }
                    $p("$altDescr\n");
                    for ($i = 0; ; ++$i) {
                        $conv = $tagInfo->PrintConv;
                        // (hidden = '' disables PrintConv in -listx output)
                        if ($tagInfo->Hidden !== null and $tagInfo->Hidden === '') break;
                        $idx = '';
                        if ($conv instanceof ConvList) {
                            if (!($i < count($conv->list))) break;
                            $conv = $conv->list[$i];
                            $idx = " index='{$i}'";
                        } else {
                            if ($i) break;
                        }
                        if (!is_array($conv)) continue;
                        // make a list of available alternate languages
                        $lcKeys = array_map('strval', array_keys($langConv));
                        sort($lcKeys, SORT_STRING);
                        $p("  <values$idx>\n");
                        self::$caseInsensitive = false;
                        // add bitmask values to main lookup
                        if (!empty($conv['BITMASK']) and is_array($conv['BITMASK'])) {
                            foreach ($conv['BITMASK'] as $key => $v) {
                                $mask = "Bit$key";
                                if (!empty($conv[$mask])) continue;
                                $conv[$mask] = $v;
                            }
                        }
                        $ckeys = array_map('strval', array_keys($conv));
                        usort($ckeys, [self::class, 'NumbersFirst']);
                        foreach ($ckeys as $key) {
                            if ($key === 'BITMASK' or $key === 'OTHER' or $key === 'Notes') continue;
                            $val = $conv[$key];
                            $val = is_array($val) ? '' : Perl::str($val);
                            $xmlVal = XMP::EscapeXML($val);
                            $xmlKey = XMP::FullEscapeXML($key);
                            $p("   <key id='{$xmlKey}'>\n");
                            // add alternate language values
                            $altConv = '';
                            foreach ($lcKeys as $l) {
                                $lv = $langConv[$l];
                                // handle indexed PrintConv entries
                                if ($lv instanceof ConvList) {
                                    $lv = $lv->list[$i] ?? null;
                                    if (!$lv) continue;
                                }
                                $lv = is_array($lv) ? ($lv[$val] ?? null) : null;
                                // ignore values that are missing or same as default
                                if ($lv === null or Perl::str($lv) === $val) continue;
                                $lv = XMP::EscapeXML($lv);
                                $altConv .= "    <val lang='{$l}'>$lv</val>\n";
                            }
                            if (empty($opts['Lang']) or !$altConv) {
                                $p("    <val lang='{$defaultLang}'>$xmlVal</val>\n");
                            }
                            $p("$altConv   </key>\n");
                        }
                        $p("  </values>\n");
                    }
                    $p(" </tag>\n");
                }
            }
            if ($didTag) $p("</table>\n\n");
        }
        $success = fwrite($fp, "</taginfo>\n") !== false;
        if ($file !== null) fclose($fp);
        return $success;
    }

    //------------------------------------------------------------------------------
    // load all lang modules into hash
    // Inputs: 0) Hash reference, 1) specific language to load (null for all)
    public static function LoadLangModules(array &$langHash, $lang = null): void
    {
        $langs = $lang ? [$lang] : Vars\ExifTool::$langs;
        foreach ($langs as $lang) {
            if ($lang === Vars\ExifTool::$defaultLang) continue;
            $xlat = 'Image\ExifTool\Vars\Lang\\' . $lang;
            if (!preg_match('/^\w+$/', (string) $lang) or !class_exists($xlat)) {
                fwrite(STDERR, "Can't load Lang::$lang\n");
                continue;
            }
            if (!$xlat::$Translate) {
                fwrite(STDERR, "Missing Info for $lang\n");
                continue;
            }
            $langHash[$lang] = $xlat::$Translate;
        }
    }

    //------------------------------------------------------------------------------
    // sort numbers first numerically, then strings alphabetically (case insensitive)
    public static function NumbersFirst($a, $b)
    {
        $a = (string) $a;
        $b = (string) $b;
        $bNum = $bDec = null;
        if (preg_match('/^(-?[0-9]+)(\.(\d*))?$/', $b, $m)) {
            $bNum = $m[1];
            $bDec = $m[3] ?? null;
        }
        if (preg_match('/^(-?[0-9]+)(\.(\d*))?$/', $a, $m)) {
            if ($bNum !== null) {
                if (self::$numbersFirst == 2 and $bNum < 0) $bNum += 1e9;
                $aInt = $m[1];
                if (self::$numbersFirst == 2 and $aInt < 0) $aInt += 1e9;
                // compare integer part as a number
                $rtnVal = $aInt <=> $bNum;
                if (!$rtnVal) {
                    $aDec = ($m[3] ?? '') ?: 0;
                    $bDec = $bDec ?: 0;
                    // compare decimal part as an integer too
                    // (so that "1.10" comes after "1.9")
                    $rtnVal = (int) $aDec <=> (int) $bDec;
                }
            } else {
                $rtnVal = -self::$numbersFirst;
            }
        } elseif ($bNum !== null) {
            $rtnVal = self::$numbersFirst;
        } else {
            $a2 = $a;
            $b2 = $b;
            // expand numbers to 3 digits (with restrictions to avoid messing up ascii-hex tags)
            $fix = static fn($s) => preg_replace_callback('/(\d+)/', static fn($mm) => sprintf('%03d', $mm[1]), $s);
            if (preg_match('/^(APP|DMC-\w+ )?[.0-9 ]*$/', $a2) and strlen($a2) < 16) $a2 = $fix($a2);
            if (preg_match('/^(APP|DMC-\w+ )?[.0-9 ]*$/', $b2) and strlen($b2) < 16) $b2 = $fix($b2);
            $rtnVal = 0;
            if (self::$caseInsensitive) $rtnVal = strcmp(strtolower($a2), strtolower($b2));
            if (!$rtnVal) $rtnVal = strcmp($a2, $b2);
        }
        return $rtnVal;
    }
}
